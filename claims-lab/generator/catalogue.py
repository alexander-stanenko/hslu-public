VALID = ("2025-01-01", "2027-12-31")


def motor(pid, plate, vehicle, partial=True, collision=False, ded_partial=300, ded_glass=200,
          valid=VALID, status="active"):
    return dict(policy_id=pid, product="motor", status=status, valid_from=valid[0], valid_to=valid[1],
                modules={"liability": True, "partial": partial, "collision": collision},
                deductibles={"partial": ded_partial, "glass": ded_glass, "collision": 1000},
                sum_insured=None, object={"plate": plate, "vehicle": vehicle})


def household(pid, sum_insured=60000, theft_outside=False, glass=False, valid=VALID):
    return dict(policy_id=pid, product="household", status="active", valid_from=valid[0], valid_to=valid[1],
                modules={"basic": True, "theft_outside": theft_outside, "glass": glass},
                deductibles={"default": 200}, sum_insured=sum_insured, object={"contents": "household contents"})


def building(pid, sum_insured=1_000_000, glass=False, valid=VALID):
    return dict(policy_id=pid, product="building", status="active", valid_from=valid[0], valid_to=valid[1],
                modules={"basic": True, "glass": glass},
                deductibles={"default": 500, "natural_hazards": 1000}, sum_insured=sum_insured,
                object={"building": "residential building"})


def cust(name, street, postcode, city):
    first = name.split()[0].lower()
    last = name.split()[-1].lower().replace("ü", "ue").replace("é", "e")
    return dict(name=name, street=street, postcode=postcode, city=city, email=f"{first}.{last}@mail.example")


